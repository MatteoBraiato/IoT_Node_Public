res_t Bsp_Do_Init(void)
{
    res_t res = RES_ALREADY_INITIALIZED;
    if(false == bspDo.init)
    {
        bspDo.init = true;
        for(uint8_t idx = 0; idx < BSP_DO_NUM; idx++)
        {
            if(ESP_OK == gpio_reset_pin(bspDoCfg[idx].pin))
            {
                /* Set the GPIO as a push/pull output */
                if(ESP_OK == gpio_set_direction(bspDoCfg[idx].pin, bspDoCfg[idx].mode))
                {
                    if(ESP_OK == gpio_set_level(bspDoCfg[idx].pin, bspDoCfg[idx].initState))
                    {
                        bspDo.init = true;
                        res = RES_OK;
                    }
                    else
                    {
                        ESP_LOGE( TAG, "Init - Set init state error!");
                        res = RES_ERROR;
                    }
                }
                else
                {
                    ESP_LOGE( TAG, "Init - Set direction error!");
                    res = RES_ERROR;
                }
            }
            else
            {
                ESP_LOGE( TAG, "Init - Reset PIN error!");
                res = RES_ERROR;
            }
        }
    }
    return res;
}

res_t Bsp_Do_Set(bsp_do_out_t out, bsp_do_pin_state_t st)
{
    res_t res = RES_ERROR_UNINITIALIZED;
    if(true == bspDo.init)
    {
        res = RES_ERROR_INVALID_PARAMETER;
        if(out < BSP_DO_NUM)
        {
            res = RES_ERROR;
            if(ESP_OK == gpio_set_level(bspDoCfg[out].pin, st))
            {
                res = RES_OK;
            }
            else
            {
                ESP_LOGE( TAG, "Set - error!");
            }
        }
        else
        {
            ESP_LOGE( TAG, "Set - invalid parameter!");
        }
    }
    return res;
}
