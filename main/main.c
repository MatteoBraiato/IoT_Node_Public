void app_main(void)
{
    ESP_LOGI("Main", "%s %d.%d.%d\n",PROJECT_NAME, PROJECT_VERSION_MAJOR, PROJECT_VERSION_MIDDLE, PROJECT_VERSION_MINOR);

    /* Bench isolation: reproduce the removed heartbeat wait without LED/RMT. */
    vTaskDelay(pdMS_TO_TICKS(1000U));

    if(RES_OK == App_Init())
    {
        xTaskCreateStaticPinnedToCore(App_Task_10s, "App wake cycle", MAIN_CYCLE_TASK_STACK_SIZE, NULL, 10, mainCycleTaskStack, &mainCycleTaskBuffer, tskNO_AFFINITY);
    }
    else
    {
        if ((true == HW_CFG_DEEPSLEEP_EN) && (false == HW_CFG_DEV_DEBUG_EN))
        {
            ESP_LOGE("Main", "Initialization failed, entering deep sleep for %d minutes...", APP_SLEEP_INTERVAL_S / 60);
            res_t shutdownRes = App_Shutdown_Peripherals();
            if (RES_OK != shutdownRes)
            {
                ESP_LOGW("Main", "Shutdown incomplete (%d), continuing to deep sleep", shutdownRes);
            }
            esp_sleep_enable_timer_wakeup((uint64_t)APP_SLEEP_INTERVAL_S * 1000000ULL);
            esp_deep_sleep_start();
        }
        else
        {
            ESP_LOGE("Main", "Initialization failed, keeping device awake for debugging");
        }
    }
}
